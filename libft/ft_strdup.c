#include "libft.h"

char	*ft_strdup(char *src)
{
	char	*cpy;
	int		i;

	cpy = malloc(ft_strlen((const char *)src) + 1);
	if (!cpy || !src)
		return (NULL);
	i = 0;
	while (src[i])
	{
		cpy[i] = src[i];
		i++;
	}
	cpy[i] = '\0';
	return (cpy);
}
